"""Original image-pair and field fixtures with independent translation truth."""

import copy
import json
import struct
from pathlib import Path

import cv2
import numpy as np

from opencv_dataflow.blocks import builtin_registry
from opencv_dataflow.core import Graph

HERE = Path(__file__).resolve().parent
PARAMETERS = {
    "alpha": 1.0,
    "delta": 10.0,
    "fixed_point_iterations": 10,
    "sor_iterations": 20,
    "alignment": "pixel_grid",
    "reject_residual_increase": True,
}


def main():
    a = cv2.GaussianBlur(
        np.random.default_rng(17).integers(0, 256, (96, 144), dtype=np.uint8), (7, 7), 1.1
    )
    b = cv2.warpAffine(
        a, np.float32([[1, 0, 2], [0, 1, 1]]), (144, 96), borderMode=cv2.BORDER_REFLECT_101
    )
    support = np.full(a.shape, 255, np.uint8)
    support[35:50, 70:85] = 0
    for name, image in (("source.png", a), ("target.png", b), ("target_support.png", support)):
        assert cv2.imwrite(str(HERE / name), image)
    initial = np.full((*a.shape, 2), [1.25, 0.5], np.float32)
    (HERE / "initial.flo").write_bytes(
        struct.pack("<fii", 202021.25, 144, 96) + initial.astype("<f4").tobytes()
    )
    truth = {
        "translation": [2.0, 1.0],
        "initial_translation": [1.25, 0.5],
        "evaluation_border": 16,
        "maximum_mean_endpoint_error": 0.6,
        "maximum_error_ratio": 0.65,
        "maximum_residual_ratio": 0.6,
        "selection_rectangle": [20, 20, 80, 50],
        "scope": "Original MIT image-space texture; no real-scene accuracy or occlusion claim",
    }
    (HERE / "truth.json").write_bytes((json.dumps(truth, indent=2) + "\n").encode())
    registry, graph = builtin_registry(), Graph()
    for key, filename, position in (
        ("source", "source.png", [0, 0]),
        ("target", "target.png", [0, 350]),
    ):
        block = graph.add(
            registry.create(
                "input.file",
                block_id=key,
                parameters={"path": filename, "path_base": "project", "color_format": "gray"},
            )
        )
        block.position = position
        block.name = "Original " + key + " texture"
    initial_block = graph.add(
        registry.create("input.flow_file", block_id="initial", parameters={"path": "initial.flo"})
    )
    initial_block.name, initial_block.position = "Deliberately biased seed field", [0, 700]
    refine = graph.add(registry.create("cv.refine_flow", block_id="refine", parameters=PARAMETERS))
    refine.position = [380, 0]
    refine.exposed_outputs += ["initial_residual", "visualization"]
    warp = graph.add(
        registry.create(
            "cv.warp_flow", block_id="warp", parameters={"direction": "source_to_target"}
        )
    )
    warp.position = [780, 0]
    warp.exposed_inputs += ["target", "flow_support"]
    for source, output, target, input_name in (
        ("source", "image", "refine", "image"),
        ("target", "image", "refine", "target"),
        ("initial", "flow", "refine", "flow"),
        ("source", "image", "warp", "image"),
        ("target", "image", "warp", "target"),
        ("refine", "flow", "warp", "flow"),
        ("refine", "support", "warp", "flow_support"),
    ):
        graph.connect(source, output, target, input_name)
    note = graph.add(registry.create("layout.comment", block_id="scope"))
    note.name, note.position, note.node_size = "Attribution and limits", [0, -420], "large"
    note.description = (
        "Original MIT fixtures/project, generated by build_example.py. Source-to-target motion "
        "is independently defined as (+2,+1) pixels, with a biased (+1.25,+0.5) seed. "
        "VariationalRefinement is local/single-scale and needs a suitable initial field. "
        "Support excludes source/donor boundaries and supplied holes; it is not visibility "
        "or accuracy confidence. Selections restrict output writes and diagnostics, not the "
        "native full-frame energy. Connect Support with Flow to downstream warping. "
        "No customer/third-party assets; captured-scene motion accuracy is unqualified."
    )
    graph.save(HERE / "flow_refinement.json")
    data = copy.deepcopy(graph.to_dict())
    item = next(block for block in data["blocks"] if block["id"] == "refine")
    item["parameters"]["maximum_mean_residual"] = 1.0
    failure = Graph.from_dict(data, registry)
    failure.save(HERE / "residual_gate_failure.json")
    failure.close()
    graph.blocks["refine"].exposed_inputs.append("target_support")
    trusted = graph.add(
        registry.create(
            "region.shape",
            block_id="trusted",
            parameters={"rectangle": [70, 35, 15, 15], "invert": True},
        )
    )
    trusted.position, trusted.name = [0, 1050], "Target support with a known hole"
    region = graph.add(
        registry.create(
            "region.shape",
            block_id="region",
            parameters={"rectangle": truth["selection_rectangle"]},
        )
    )
    region.position, region.name = [380, 400], "Selected source output region"
    graph.connect("source", "image", "region", "image")
    graph.connect("region", "region", "refine", "region")
    graph.connect("target", "image", "trusted", "image")
    graph.connect("trusted", "mask", "refine", "target_support")
    graph.save(HERE / "partial_support.json")
    graph.close()


if __name__ == "__main__":
    main()
