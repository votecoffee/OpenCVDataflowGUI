"""Original native structured symbols; physical image order never supplies fragment IDs."""

import hashlib
import json
from pathlib import Path

import cv2
import numpy as np

from opencv_dataflow.blocks import builtin_registry
from opencv_dataflow.core import Graph
from opencv_dataflow.qr_encoding import EncodeQRCode

HERE = Path(__file__).resolve().parent
TEXT = "PART-0042/LOT-A-INSPECTION-1234567890"
CASES = (
    "shuffled_scene",
    "shuffled_group",
    "missing",
    "duplicate",
    "mismatched",
    "mixed_count",
    "collision_digest",
    "damaged_header",
)


def symbols(text=TEXT, count=3):
    block = EncodeQRCode(
        parameters={
            "text": text,
            "mode": "structured_append",
            "structure_number": count,
            "pixels_per_module": 6,
        }
    )
    result = block.execute({})
    assert result is not None, block.error
    return [np.asarray(packet.value).copy() for packet in result.outputs["symbols"].items]


def assets():
    original = symbols()
    foreign = symbols(TEXT + "X")
    collision = symbols(TEXT[:-2] + "81")
    two = symbols(TEXT, 2)
    data = {f"part_{i}.png": value for i, value in enumerate(original)}
    selections = {
        "shuffled_scene": [original[i] for i in (2, 0, 1)],
        "missing": [original[2], original[0]],
        "duplicate": [original[i] for i in (2, 0, 1, 1)],
        "mismatched": [original[0], original[1], foreign[2]],
        "mixed_count": [original[0], original[2], two[1]],
        "collision_digest": [original[0], original[1], collision[2]],
    }
    damaged = original[1].copy()
    # First data module (bottom right of the core). Native payload RS correction
    # recovers this, while conservative raw-module header validation rejects it.
    x = y = (4 + 21 - 1) * 6
    damaged[y : y + 6, x : x + 6] = 255 - damaged[y : y + 6, x : x + 6]
    selections["damaged_header"] = [original[0], damaged, original[2]]
    placements = {}
    for case, entries in selections.items():
        side = max(max(image.shape) for image in entries)
        scene = np.full((side + 40, len(entries) * (side + 32) + 32), 255, np.uint8)
        placements[case] = []
        for i, image in enumerate(entries):
            x, y = 32 + i * (side + 32), 20
            scene[y : y + image.shape[0], x : x + image.shape[1]] = image
            placements[case].append([x + 24, y + 24])
        data[f"{case}.png"] = scene
    return data, placements


def build():
    directory = HERE / "assets"
    directory.mkdir(exist_ok=True)
    data, placements = assets()
    for name, image in data.items():
        ok, encoded = cv2.imencode(".png", image)
        assert ok
        (directory / name).write_bytes(encoded.tobytes())
    registry = builtin_registry()
    for case in CASES:
        graph = Graph()
        group = case == "shuffled_group"
        parameters = {"path_base": "project", "color_format": "gray", "repeat": "stop"}
        if group:
            parameters.update(
                source_mode="files", paths=[f"assets/part_{i}.png" for i in (2, 0, 1)]
            )
        else:
            parameters["path"] = f"assets/{case}.png"
        source = graph.add(registry.create("input.file", block_id="source", parameters=parameters))
        source.position = [0, 0]
        reader = graph.add(
            registry.create(
                "inspect.read_qr_append",
                block_id="assemble",
                parameters={
                    "expected_parts": 3,
                    "expected_sha256": hashlib.sha256(TEXT.encode()).hexdigest(),
                },
            )
        )
        reader.position = [800, 0]
        if group:
            batch = graph.add(
                registry.create("flow.batch", block_id="batch", parameters={"size": 3})
            )
            batch.position = [400, 0]
            graph.connect("source", "image", "batch", "item_1")
            graph.connect("batch", "group", "assemble", "images")
        else:
            graph.connect("source", "image", "assemble", "image")
        note = graph.add(registry.create("layout.comment", block_id="attribution"))
        note.name, note.position, note.node_size = (
            "Original structured QR fixture",
            [0, -440],
            "large",
        )
        note.description = (
            "Original MIT images, payloads and projects by OpenCVDataflowGUI contributors, "
            "generated by build_example.py with native QRCodeEncoder. No customer/third-party "
            "images. Decoder reads actual module headers; filename, visual order and generator "
            "payload metadata are not identity. All projects pin the expected full-payload SHA256. "
            "Only shuffled_scene/group complete; the other projects deliberately reject missing, "
            "duplicate, foreign/count-mismatched, parity-colliding or damaged fragments. "
            "Header verification conservatively requires uncorrected module/codeword integrity. "
            "XOR parity alone cannot distinguish every mixed set. QR block-layout tables in the "
            "application derive from Project Nayuki's MIT QR Code generator library; its full "
            "notice and pinned source are retained in qr_rs_tables.py."
        )
        graph.save(HERE / f"{case}.json")
        graph.close()
    truth = {
        "creator": "OpenCVDataflowGUI contributors",
        "license": "MIT",
        "text": TEXT,
        "sha256": hashlib.sha256(TEXT.encode()).hexdigest(),
        "part_count": 3,
        "success_cases": ["shuffled_scene", "shuffled_group"],
        "cases": list(CASES),
        "scene_core_top_lefts": placements,
        "asset_sha256": {
            path.name: hashlib.sha256(path.read_bytes()).hexdigest()
            for path in sorted(directory.glob("*.png"))
        },
    }
    (HERE / "truth.json").write_bytes((json.dumps(truth, indent=2) + "\n").encode())


if __name__ == "__main__":
    build()
