"""Original moving-part fixture and bounded native animation workflows (MIT)."""

import json
from pathlib import Path

import cv2
import numpy as np

from opencv_dataflow.blocks import builtin_registry
from opencv_dataflow.core import Graph

HERE = Path(__file__).resolve().parent


def reference_frames():
    y, x = np.indices((96, 160))
    frames = []
    for index in range(3):
        image = np.dstack((18 + x // 5 + index * 7, 25 + y // 4, 30 + (x + y) // 7)).astype(
            np.uint8
        )
        cv2.circle(image, (36 + 40 * index, 50), 12, (230, 230, 230), -1)
        frames.append(image)
    return frames


def make_project(case, registry):
    graph = Graph()

    def add(type_id, block_id, position, parameters=None):
        block = graph.add(registry.create(type_id, block_id=block_id, parameters=parameters or {}))
        block.position = position
        return block

    source = add(
        "input.animation_file",
        "source",
        [0, 0],
        {"path": "assets/moving_part.png", "preview_frame": 1},
    )
    source.description = (
        "Three original frames: circle centers x=36, 76, 116; y=50. Durations 80/120/200 ms."
    )
    if case == "frame_inspection":
        add("flow.unbatch", "frames", [420, 0])
        add("cv.threshold", "threshold", [840, 0], {"value": 200})
        add("inspect.components", "inspect", [1260, 0], {"expected_count": 1})
        graph.connect("source", "frames", "frames", "group")
        graph.connect("frames", "value", "threshold", "image")
        graph.connect("threshold", "image", "inspect", "image")
    else:
        codec = (
            "webp"
            if case in ("webp_roundtrip", "write_webp")
            else "gif"
            if case.startswith("gif")
            else "apng"
        )
        parameters = {"codec": codec}
        if case.startswith("gif"):
            parameters.update(
                duration_mode="explicit",
                durations_ms=[83, 129, 208],
                gif_timing="exact" if case == "gif_timing_failure" else "floor_10ms",
            )
        if case == "write_webp":
            parameters["path"] = "animation-output.webp"
            add("output.animation_file", "write", [420, 0], parameters)
            graph.connect("source", "frames", "write", "frames")
        else:
            add("cv.encode_animation", "encode", [420, 0], parameters)
            add("cv.decode_animation", "decode", [840, 0], {"preview_frame": 1})
            graph.connect("source", "frames", "encode", "frames")
            graph.connect("encode", "encoded", "decode", "encoded")
            if not case.startswith("gif"):
                add("cv.image_norm", "verify", [1260, 0], {"check_threshold": True, "maximum": 0.0})
                graph.connect("decode", "image", "verify", "image")
                graph.connect("source", "image", "verify", "reference")
    note = add("layout.comment", "attribution", [0, -400])
    note.name, note.node_size = "Original MIT fixture and animation contract", "large"
    note.description = (
        "Original MIT synthetic images and projects, generated by build_example.py. No customer "
        "or third-party images. Three white circles have known centers and a fixed radius. "
        "APNG and lossless WebP must return exact visible samples in order at 80/120/200 ms. "
        "GIF reduces color and uses 10-ms timing: 83/129/208 explicitly quantizes to 80/120/200. "
        "The exact GIF timing example intentionally rejects those durations and emits nothing. "
        "The inspection project unbatches all three frames into ordinary image tools; the last "
        "visible result is frame 2 at x=116. One file acquisition ticket owns the group, with "
        "frame indices/timing on each image. Writer output never replaces an existing file. "
        "These are bounded offline data transformations; display playback pacing is not added."
    )
    return graph


def main():
    assets = HERE / "assets"
    assets.mkdir(exist_ok=True)
    frames = reference_frames()
    animation = cv2.Animation()
    animation.frames, animation.durations, animation.loop_count = frames, [80, 120, 200], 3
    ok, data = cv2.imencodeanimation(".png", animation)
    assert ok
    (assets / "moving_part.png").write_bytes(data.tobytes())
    for index, image in enumerate(frames):
        ok, data = cv2.imencode(".png", image)
        assert ok
        (assets / f"frame_{index}.png").write_bytes(data.tobytes())
    truth = {
        "license": "MIT",
        "creator": "OpenCVDataflowGUI contributors",
        "frame_count": 3,
        "durations_ms": [80, 120, 200],
        "loop_count": 3,
        "circle_centers": [[36, 50], [76, 50], [116, 50]],
        "circle_radius_pixels": 12,
        "gif_requested_ms": [83, 129, 208],
        "gif_stored_ms": [80, 120, 200],
        "lossless_maximum_error": 0,
        "scope": "Original offline controls, not timed camera playback or codec robustness grading",
    }
    (HERE / "truth.json").write_bytes((json.dumps(truth, indent=2) + "\n").encode())
    registry = builtin_registry()
    for case in (
        "apng_roundtrip",
        "webp_roundtrip",
        "gif_timing",
        "gif_timing_failure",
        "frame_inspection",
        "write_webp",
    ):
        graph = make_project(case, registry)
        graph.save(HERE / (case + ".json"))
        graph.close()


if __name__ == "__main__":
    main()
