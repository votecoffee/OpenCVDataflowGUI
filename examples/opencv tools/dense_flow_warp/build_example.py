"""Original RGB16 translation truth and explicit flow/consistency defect fixtures."""

import copy
import json
import struct
from pathlib import Path

import cv2
import numpy as np

from opencv_dataflow.blocks import builtin_registry
from opencv_dataflow.core import Graph

HERE = Path(__file__).resolve().parent


def save_flow(name, vectors):
    h, w = vectors.shape[:2]
    (HERE / name).write_bytes(
        struct.pack("<fii", 202021.25, w, h) + vectors.astype("<f4").tobytes()
    )


def main():
    h, w, dx, dy = 96, 128, 5, 3
    y, x = np.indices((h, w))
    intensity = 1000 + 101 * x + 151 * y + ((x - 65) ** 2 + (y - 46) ** 2 < 144) * 12000
    source = np.stack((intensity + 300, intensity + 100, intensity + 700), axis=2).astype(np.uint16)
    target = np.zeros_like(source)
    target[dy:, dx:] = source[:-dy, :-dx]
    for name, image in (("source.png", source), ("target.png", target)):
        assert cv2.imwrite(str(HERE / name), image[..., ::-1])
    forward = np.full((h, w, 2), [dx, dy], np.float32)
    backward = -forward
    save_flow("forward.flo", forward)
    save_flow("backward.flo", backward)
    broken = backward.copy()
    broken[16:20, 20:25] = np.nan
    save_flow("invalid_pull.flo", broken)
    disagreement = forward.copy()
    disagreement[27:39, 35:53, 0] += 3
    save_flow("inconsistent_forward.flo", disagreement)
    truth = {
        "image_size": [w, h],
        "translation": [dx, dy],
        "translation_coverage": (w - dx) * (h - dy),
        "invalid_rectangle": [20, 16, 5, 4],
        "occlusion_proxy_rectangle": [40, 30, 18, 12],
        "invalid_count": 20,
        "occlusion_proxy_count": 216,
        "scope": "Known motion and deliberately inconsistent fields; no physical occlusion truth",
    }
    (HERE / "truth.json").write_bytes((json.dumps(truth, indent=2) + "\n").encode())
    registry, graph = builtin_registry(), Graph()

    def add(kind, ident, name, position, parameters=None):
        value = graph.add(registry.create(kind, block_id=ident, parameters=parameters or {}))
        value.name, value.position = name, list(position)
        return value

    add(
        "input.file",
        "source",
        "Original 16-bit RGB",
        (0, 0),
        {
            "path": "source.png",
            "path_base": "project",
            "color_format": "rgb",
            "pixel_depth": "unchanged",
        },
    )
    add(
        "input.file",
        "target",
        "Known target grid and reference",
        (0, 450),
        {
            "path": "target.png",
            "path_base": "project",
            "color_format": "rgb",
            "pixel_depth": "unchanged",
        },
    )
    add(
        "input.flow_file",
        "forward",
        "Known source-to-target motion",
        (330, 0),
        {"path": "forward.flo"},
    )
    add("input.flow_file", "reverse", "Known reverse motion", (330, 450), {"path": "backward.flo"})
    warp = add(
        "cv.warp_flow",
        "warp",
        "Move source onto target grid",
        (700, 0),
        {"direction": "source_to_target", "interpolation": "nearest", "consistency": "required"},
    )
    warp.exposed_inputs += ["target", "reverse_flow"]
    warp.exposed_outputs += ["invalid", "uncovered", "occluded", "coverage_preview"]
    note = add("layout.comment", "scope", "Original truth and interpretation", (0, -470))
    note.node_size = "large"
    note.description = (
        "Original project fixture (MIT), generated by build_example.py. RGB16 samples move +5,+3 "
        "by independent array slicing; supported pixels must match exactly. Source ticket stays "
        "primary while coordinates use the explicit target anchor. Flow files store only vectors, "
        "so their grid association is size-only. The second project separates nonfinite flow, "
        "out-of-frame donors and reverse-field disagreement. Disagreement is an occlusion proxy, "
        "not proof of physical occlusion; arbitrary forward-field invertibility is not established."
    )
    for source_id, output, target_input in (
        ("source", "image", "image"),
        ("target", "image", "target"),
        ("forward", "flow", "flow"),
        ("reverse", "flow", "reverse_flow"),
    ):
        graph.connect(source_id, output, "warp", target_input)
    graph.save(HERE / "dense_flow_warp.json")
    baseline = graph.to_dict()
    proxy = copy.deepcopy(baseline)
    by_id = {b["id"]: b for b in proxy["blocks"]}
    by_id["forward"]["parameters"]["path"] = "invalid_pull.flo"
    by_id["reverse"]["parameters"]["path"] = "inconsistent_forward.flo"
    by_id["warp"]["parameters"]["direction"] = "target_to_source"
    project = Graph.from_dict(proxy, registry)
    project.save(HERE / "invalid_and_occlusion_proxy.json")
    project.close()
    next(b for b in baseline["blocks"] if b["id"] == "warp")["parameters"]["minimum_coverage"] = (
        0.99
    )
    project = Graph.from_dict(baseline, registry)
    project.save(HERE / "coverage_gate_failure.json")
    project.close()
    graph.close()


if __name__ == "__main__":
    main()
