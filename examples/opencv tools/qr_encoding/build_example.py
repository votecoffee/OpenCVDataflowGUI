"""Original QR payloads and native generation/readback projects."""

import json
from pathlib import Path

import cv2

from opencv_dataflow.blocks import builtin_registry
from opencv_dataflow.core import Graph

HERE = Path(__file__).resolve().parent
CASES = {
    "qr_roundtrip": {"text": "PART-0042/LOT-A", "mode": "alphanumeric", "correction_level": "H"},
    "qr_unicode": {"text": "Caf\u00e9 \u6f22\u5b57 / PART-42", "mode": "eci_utf8"},
    "structured_append": {
        "text": "PART-0042/LOT-A-INSPECTION-1234567890",
        "mode": "structured_append",
        "structure_number": 3,
        "sheet_columns": 2,
    },
    "capacity_failure": {"text": "x" * 400, "mode": "byte", "version": 1},
}


def main():
    registry = builtin_registry()
    truth = {
        "payloads": {name: p["text"] for name, p in CASES.items()},
        "structured_count": 3,
        "scope": "Original MIT payloads; QR generation without print grading or ordered recovery",
    }
    (HERE / "truth.json").write_bytes(
        (json.dumps(truth, indent=2, ensure_ascii=False) + "\n").encode()
    )
    for name, parameters in CASES.items():
        graph = Graph()
        generator = graph.add(
            registry.create("cv.encode_qr", block_id="generate", parameters=parameters)
        )
        generator.position = [0, 0]
        generator.exposed_outputs += ["symbols", "modules", "text"]
        if name in ("qr_roundtrip", "qr_unicode"):
            reader = graph.add(
                registry.create("inspect.read_qr", block_id="read", parameters={"mode": "single"})
            )
            reader.position = [440, 0]
            graph.connect("generate", "image", "read", "image")
        note = graph.add(registry.create("layout.comment", block_id="scope"))
        note.name, note.position, note.node_size = (
            "Attribution and label contract",
            [0, -420],
            "large",
        )
        note.description = (
            "Original MIT payloads and projects, generated by build_example.py using native "
            "OpenCV QRCodeEncoder. No customer or third-party images. Integer module scaling "
            "and an explicit four-module quiet zone preserve binary edges. Ordinary and UTF-8 "
            "ECI labels read back through the native reader. Structured append generates three "
            "ordered native images in a FlowGroup plus a contact sheet; the sheet is a preview, "
            "not a complete decoded inspection result. Ordered recovery of missing/duplicated "
            "fragments remains S1-162. The capacity project intentionally fails without output. "
            "Result-graphics bounds are separate from the pristine output label. No print-quality "
            "grade or scanner/lighting robustness qualification is claimed."
        )
        graph.save(HERE / (name + ".json"))
        if name == "qr_roundtrip":
            result = generator.execute({})
            assert result is not None, generator.error
            assert cv2.imwrite(str(HERE / "label_reference.png"), result.outputs["image"])
        graph.close()


if __name__ == "__main__":
    main()
