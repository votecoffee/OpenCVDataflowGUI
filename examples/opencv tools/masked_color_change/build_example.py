"""Original colored step fixture for gradient-domain color editing."""

import json
from pathlib import Path

import cv2
import numpy as np

from opencv_dataflow.blocks import builtin_registry
from opencv_dataflow.core import Graph

HERE = Path(__file__).resolve().parent


def main():
    image = np.full((128, 192, 3), 40, np.uint8)
    image[30:98, 50:142] = [80, 110, 150]
    assert cv2.imwrite(str(HERE / "surface.png"), image)
    truth = {
        "source_bgr": [80, 110, 150],
        "background_bgr": [40, 40, 40],
        "expected_center_bgr": [68, 110, 194],
        "maximum_center_error_dn": 2,
        "left_edge_x": 50,
        "right_edge_x": 142,
        "edge_tolerance_pixels": 1,
        "measurement_rectangle": [65, 40, 62, 48],
        "selected_rectangle": [20, 12, 152, 104],
        "scope": "Original MIT constant-boundary fixture with independently scaled color steps",
    }
    (HERE / "truth.json").write_bytes((json.dumps(truth, indent=2) + "\n").encode())
    registry, graph = builtin_registry(), Graph()

    def add(kind, ident, name, position, parameters=None):
        block = graph.add(registry.create(kind, block_id=ident, parameters=parameters or {}))
        block.name, block.position = name, list(position)
        return block

    source = add(
        "input.file",
        "source",
        "Original colored surface",
        (0, 0),
        {"path": "surface.png", "path_base": "project"},
    )
    region = add(
        "region.shape",
        "selection",
        "Editable surface selection",
        (300, 350),
        {"rectangle": truth["selected_rectangle"]},
    )
    edited = add(
        "cv.color_change",
        "edit",
        "Scale selected color gradients",
        (650, 0),
        {"red_mul": 1.4, "green_mul": 1.0, "blue_mul": 0.7},
    )
    note = add("layout.comment", "scope", "Original fixture and limitations", (0, -470))
    note.node_size = "large"
    note.description = (
        "Original project fixture and graph (MIT), generated by build_example.py. "
        "The BGR surface [80,110,150] lies on [40,40,40]. With red=1.4, green=1, blue=0.7, "
        "the independent step reference is [68,110,194]. Boundary positions are x=50 and 142. "
        "This is native gradient-domain color editing, not reference-palette matching, "
        "white balance or colorimetric calibration. No customer or upstream image content."
    )
    graph.connect(source.id, "image", region.id, "image")
    graph.connect(source.id, "image", edited.id, "image")
    graph.connect(region.id, "region", edited.id, "region")
    graph.save(HERE / "masked_color_change.json")
    graph.close()


if __name__ == "__main__":
    main()
