"""Build an original controlled surface fixture and native photo-edit graph."""

import json
from pathlib import Path

import cv2
import numpy as np

from opencv_dataflow.blocks import builtin_registry
from opencv_dataflow.core import Graph

HERE = Path(__file__).resolve().parent


def main():
    y, x = np.indices((128, 192))
    base = 65 + 65 * (x >= 96)
    highlight = 65 * np.exp(-(((x - 77) / 29) ** 2) - ((y - 64) / 55) ** 2)
    texture = 5 * np.sin(x * np.pi / 2) * np.sin(y * np.pi / 2)
    gray = np.rint(np.clip(base + highlight + texture, 0, 255)).astype(np.uint8)
    image = np.repeat(gray[..., None], 3, axis=2)
    assert cv2.imwrite(str(HERE / "surface.png"), image)
    truth = {
        "image_size": [192, 128],
        "step_boundary_x": 96,
        "selected_rectangle": [16, 12, 160, 104],
        "profile_y_range": [40, 88],
        "profile_x_range": [30, 83],
        "texture_rectangle": [38, 35, 44, 59],
        "illumination_max_span_ratio": 0.7,
        "texture_max_rms_ratio": 0.3,
        "boundary_tolerance_pixels": 1,
        "illumination_min_step_dn": 5,
        "texture_min_step_dn": 35,
        "scope": "Original synthetic samples; no physical illumination or defect ground truth",
    }
    (HERE / "truth.json").write_bytes((json.dumps(truth, indent=2) + "\n").encode())
    registry = builtin_registry()
    graph = Graph()

    def add(kind, ident, title, position, parameters=None):
        block = graph.add(registry.create(kind, block_id=ident, parameters=parameters or {}))
        block.name, block.position = title, list(position)
        return block

    source = add(
        "input.file",
        "source",
        "Original controlled surface",
        (0, 0),
        {"path": "surface.png", "path_base": "project"},
    )
    region = add(
        "region.shape",
        "selection",
        "Shared editable selection",
        (310, 350),
        {"rectangle": truth["selected_rectangle"]},
    )
    illumination = add("cv.illumination_change", "illumination", "Reduce broad variation", (660, 0))
    texture_block = add(
        "cv.texture_flattening",
        "texture",
        "Suppress weak texture",
        (660, 520),
        {"low_threshold": 50, "high_threshold": 150, "kernel_size": 3},
    )
    note = add("layout.comment", "scope", "Source and measurement scope", (0, -470))
    note.node_size = "large"
    note.description = (
        "Original project fixture (MIT), generated by build_example.py. A known step at x=96, "
        "a broad intensity bump and weak periodic texture exercise two native OpenCV edits. "
        "Compare reports, gradient/selection masks and maximum-channel change maps. Native "
        "illumination editing also reduces boundary contrast; it is not flat-field calibration "
        "or recovery of clipped glare. The tests independently measure boundary position, "
        "variation and texture. No customer or upstream sample imagery is used."
    )
    graph.connect(source.id, "image", region.id, "image")
    for block in (illumination, texture_block):
        graph.connect(source.id, "image", block.id, "image")
        graph.connect(region.id, "region", block.id, "region")
    graph.save(HERE / "masked_photo_correction.json")
    graph.close()


if __name__ == "__main__":
    main()
