"""Original translation, scale and deliberate disappearance fixtures for color tracking."""

import copy
import json
from pathlib import Path

import cv2
import numpy as np

from opencv_dataflow.blocks import builtin_registry
from opencv_dataflow.core import Graph

HERE = Path(__file__).resolve().parent


def main():
    truth = {"translation": [], "scale": [], "loss": []}
    for kind in ("translation", "scale"):
        folder = HERE / kind
        folder.mkdir(exist_ok=True)
        frames = 8 if kind == "translation" else 12
        for index in range(frames):
            image = np.full((96, 144, 3), 35, np.uint8)
            cv2.rectangle(image, (110, 15), (130, 35), (25, 25, 210), -1)
            present = index < 8 or index == 11
            center = (
                [41.5 + 2 * index, 37.5 + index]
                if kind == "translation"
                else [45 + 2 * index, 42 + index]
            )
            if present:
                if kind == "translation":
                    cv2.rectangle(
                        image,
                        (30 + 2 * index, 30 + index),
                        (53 + 2 * index, 45 + index),
                        (27, 200, 27),
                        -1,
                    )
                else:
                    cv2.ellipse(
                        image,
                        tuple(center),
                        (12 + round(index * 0.7), 7 + round(index * 0.3)),
                        25,
                        0,
                        360,
                        (27, 200, 27),
                        -1,
                    )
            assert cv2.imwrite(str(folder / f"{index:02d}.png"), image)
            record = {"index": index, "present": present, "center": center if present else None}
            if kind == "translation":
                truth["translation"].append(record)
            elif index < 8:
                truth["scale"].append(record)
            if kind == "scale":
                truth["loss"].append(record)
    truth.update(
        center_tolerance_pixels=3.0,
        camshift_minimum_scale_growth=1.4,
        loss_indices=[8, 9, 10],
        expired_index=11,
        scope="Original MIT image-space fixtures; no physical identity or dimension claim",
    )
    (HERE / "truth.json").write_bytes((json.dumps(truth, indent=2) + "\n").encode())
    registry = builtin_registry()
    for method, kind in (("mean_shift", "translation"), ("cam_shift", "scale")):
        graph = Graph()
        source = graph.add(
            registry.create(
                "input.file",
                block_id="source",
                parameters={
                    "path": f"{kind}/00.png",
                    "source_mode": "files",
                    "paths": [f"{kind}/{i:02d}.png" for i in range(8)],
                    "path_base": "project",
                    "color_format": "rgb" if kind == "scale" else "bgr",
                },
            )
        )
        source.name, source.position = "Original controlled frames", [0, 0]
        tracker = graph.add(
            registry.create(
                "sequence.color_tracker",
                block_id="tracker",
                parameters={
                    "method": method,
                    "initial_bounds": [30, 30, 24, 16] if kind == "translation" else [],
                    "pose_mode": "principal_axis" if kind == "scale" else "center_only",
                },
            )
        )
        tracker.name, tracker.position = "Track one taught color region", [650, 0]
        tracker.exposed_outputs += ["tracked_region", "probability", "geometry"]
        graph.connect("source", "image", "tracker", "image")
        if kind == "scale":
            seed = graph.add(
                registry.create(
                    "region.shape", block_id="seed", parameters={"rectangle": [30, 30, 30, 24]}
                )
            )
            seed.name, seed.position = "Editable teaching region", [320, 400]
            graph.connect("source", "image", "seed", "image")
            graph.connect("seed", "region", "tracker", "seed")
        note = graph.add(registry.create("layout.comment", block_id="scope"))
        note.name, note.position, note.node_size = (
            "Source and tracking contract",
            [0, -470],
            "large",
        )
        note.description = (
            "Original project fixtures and graph (MIT), generated by build_example.py. "
            "Green target positions and scale changes are independently defined in truth.json; "
            "the red distractor is deliberately a different color. First frame teaches, then "
            "accepted frames yield current-ticket geometry. CamShift ellipse sizes describe color "
            "mass, not physical part dimensions; principal axes have 180-degree ambiguity. "
            "After three lost frames, expiry requires explicit reset/reseed. No customer or "
            "third-party image content; no robust identity claim for same-color distractors."
        )
        graph.save(HERE / f"{method}.json")
        if kind == "scale":
            data = copy.deepcopy(graph.to_dict())
            next(b for b in data["blocks"] if b["id"] == "source")["parameters"]["paths"] = [
                f"scale/{i:02d}.png" for i in range(12)
            ]
            failure = Graph.from_dict(data, registry)
            failure.save(HERE / "loss_and_expiry.json")
            failure.close()
        graph.close()


if __name__ == "__main__":
    main()
